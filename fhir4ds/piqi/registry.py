"""Resolver for packaged PIQI canonicals → resources.

Reads the JSON files under ``fhir4ds/piqi/resources/`` (generated by
``python3 -m fhir4ds.piqi.authoring``) so ``SQLQueryRunner(conn,
piqi_resolver())`` works with zero runner changes (FDD invariant 3).
"""

from __future__ import annotations

import functools
import json
import typing as _t
from pathlib import Path

from .authoring import CANONICAL_BASE, DATA_CLASS_TO_VIEW, view_canonical

_RESOURCES_DIR = Path(__file__).parent / "resources"


@functools.lru_cache(maxsize=1)
def _load_registry() -> dict[str, dict]:
    registry: dict[str, dict] = {}
    views_dir = _RESOURCES_DIR / "views"
    for path in sorted(views_dir.glob("*.json")):
        registry[view_canonical(path.stem)] = json.loads(
            path.read_text(encoding="utf-8"))
    for sub in ("sams", "rubrics"):
        for path in sorted((_RESOURCES_DIR / sub).glob("*.sqlquery.json")):
            doc = json.loads(path.read_text(encoding="utf-8"))
            registry[doc["url"]] = doc
    return registry


def piqi_resolver() -> _t.Callable[[str], dict]:
    """Return a ``DependencyResolver`` over the packaged PIQI resources."""

    def resolve(canonical: str) -> dict:
        registry = _load_registry()
        try:
            return registry[canonical]
        except KeyError:
            raise KeyError(
                f"Unknown PIQI canonical {canonical!r} "
                f"(base {CANONICAL_BASE!r})") from None

    return resolve


def get_view(view_name: str) -> dict:
    """Return a packaged PIQI ViewDefinition dict by name."""
    return _load_registry()[view_canonical(view_name)]


def get_sam(instance_id: str) -> dict:
    """Return a packaged SAM SQLQuery Library by instance id.

    Accepts either the bare instance id (``labresult-test-iscomplete``)
    or the Library id (``piqi-sam-labresult-test-iscomplete``).
    """
    lib_id = instance_id if instance_id.startswith("piqi-sam-") else (
        "piqi-sam-" + instance_id)
    return _load_registry()[CANONICAL_BASE + "Library/" + lib_id]


def get_rubric(name: str) -> dict:
    """Return a packaged rubric SQLQuery Library (incl. criteria metadata)."""
    return _load_registry()[CANONICAL_BASE + "Library/piqi-rubric-" + name]


def all_views() -> list[str]:
    return sorted(DATA_CLASS_TO_VIEW.values())


__all__ = ["piqi_resolver", "get_view", "get_sam", "get_rubric", "all_views"]
