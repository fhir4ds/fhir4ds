"""AMUX-134 evaluation gates: golden-set P/R, determinism, scale smoke.

The harness Joel gated the feature on (design doc §Gates + gates brief
2026-11-17):

1. Precision/recall over the synthetic golden corpus (fixtures/golden_corpus.json,
   regenerated by scripts/gen_matching_golden.py). Floors: precision >= 0.95,
   recall >= 0.90; additionally NO regression below the recorded baseline in
   fhir4ds/matching/evaluation/baseline.json. Ambiguous outcomes count as not
   matched (recall) but never as false positives (precision).
2. Exploratory check: every labeled duplicate is caught by at least one
   Category-1 rule in isolation — the generator must not ship labels the
   engine legitimately cannot satisfy.
3. Determinism: the full pipeline run twice with shuffled insertion order
   produces an identical sha256 over sorted linkage JSON, sorted membership
   rows, and sorted audit rows (modulo run_id/rowid).
4. Scale smoke (marked slow, still run): 2,000 patients indexed + one
   match_patient under a generous wall-clock ceiling (regression tripwire).
"""

from __future__ import annotations

import hashlib
import json
import random
import time

import duckdb
import pytest

from fhir4ds.matching import (
    build_membership,
    create_audit_tables,
    create_linkage_tables,
    create_matching_tables,
    index_patient,
    load_linkage_resources,
    match_corpus,
    match_patient,
)
from fhir4ds.matching.evaluation import (
    PRECISION_FLOOR,
    RECALL_FLOOR,
    catching_rules,
    evaluate_golden,
    load_baseline,
    load_golden_corpus,
)

CORPUS = load_golden_corpus()


def _indexed_conn(patients: list[dict]) -> duckdb.DuckDBPyConnection:
    conn = duckdb.connect()
    create_matching_tables(conn)
    create_linkage_tables(conn)
    create_audit_tables(conn)
    for resource in patients:
        index_patient(conn, resource)
    return conn


# ---------------------------------------------------------------------------
# Gate 1: precision / recall vs golden labels + baseline regression
# ---------------------------------------------------------------------------


def test_golden_precision_recall_gate():
    conn = _indexed_conn(CORPUS["patients"])
    metrics = evaluate_golden(conn, CORPUS)
    baseline = load_baseline()

    assert metrics.precision >= PRECISION_FLOOR, (
        f"precision {metrics.precision:.4f} below floor {PRECISION_FLOOR}: "
        f"false positives {metrics.false_positives}"
    )
    assert metrics.recall >= RECALL_FLOOR, (
        f"recall {metrics.recall:.4f} below floor {RECALL_FLOOR}: "
        f"misses {json.dumps(metrics.misses, indent=2)}"
    )
    # Regression gate: never below the recorded baseline.
    assert metrics.precision >= baseline["precision"], (
        f"precision regression: {metrics.precision:.4f} < baseline "
        f"{baseline['precision']:.4f}"
    )
    assert metrics.recall >= baseline["recall"], (
        f"recall regression: {metrics.recall:.4f} < baseline "
        f"{baseline['recall']:.4f}"
    )
    # Corpus shape guard: the baseline is only meaningful for this corpus.
    assert metrics.duplicate_pairs == baseline["duplicate_pairs"]
    assert metrics.non_duplicate_pairs == baseline["non_duplicate_pairs"]


def test_golden_corpus_composition():
    labels = [p["label"] for p in CORPUS["pairs"]]
    kinds = [p["kind"] for p in CORPUS["pairs"]]
    assert labels.count("duplicate") == 60
    assert labels.count("non_duplicate") == 60
    hard = [k for k in kinds if k in ("sibling_hard", "twin_hard")]
    assert len(hard) == 30, "half the negatives must be hard family negatives"
    # every pair references two distinct indexed patients
    ids = {r["id"] for r in CORPUS["patients"]}
    for pair in CORPUS["pairs"]:
        assert pair["a"] != pair["b"]
        assert {pair["a"], pair["b"]} <= ids


def test_ambiguous_outcomes_are_not_false_positives():
    """Scoring semantics pin: ambiguous pairs (if any) hurt recall only."""
    conn = _indexed_conn(CORPUS["patients"])
    metrics = evaluate_golden(conn, CORPUS)
    labeled = {tuple(sorted((p["a"], p["b"]))): p["label"] for p in CORPUS["pairs"]}
    duplicates = {pair for pair, label in labeled.items() if label == "duplicate"}
    linkage_pairs = {
        tuple(sorted((lid.split("|")[0][len("Patient/"):], lid.split("|")[1][len("Patient/"):])))
        for (lid,) in conn.execute("SELECT linkage_id FROM linkage").fetchall()
    }
    assert metrics.true_positives == len(linkage_pairs & duplicates)
    assert metrics.false_positive_count == len(linkage_pairs - set(labeled))
    # ambiguous outcomes never create linkage rows -> never false positives
    assert metrics.false_positive_count == 0
    assert metrics.true_positives == 60


# ---------------------------------------------------------------------------
# Gate 2: exploratory — every labeled duplicate catchable by >= 1 rule
# ---------------------------------------------------------------------------


def test_every_labeled_duplicate_catchable_by_a_category1_rule():
    conn = _indexed_conn(CORPUS["patients"])
    uncatchable = []
    for pair in CORPUS["pairs"]:
        if pair["label"] != "duplicate":
            continue
        rules = set(
            catching_rules(conn, pair["a"], pair["b"])
            + catching_rules(conn, pair["b"], pair["a"])
        )
        if not rules:
            uncatchable.append(pair)
    assert not uncatchable, (
        "golden set contains duplicates the engine legitimately cannot "
        "catch — adjust the GENERATOR, not the engine: "
        f"{[p['kind'] for p in uncatchable]}"
    )


def test_no_negative_pair_caught_by_isolated_rules():
    """Exploratory mirror: no labeled negative matches under ANY single rule
    (would indicate the generator ships indistinguishable negatives)."""
    conn = _indexed_conn(CORPUS["patients"])
    caught = []
    for pair in CORPUS["pairs"]:
        if pair["label"] != "non_duplicate":
            continue
        rules = set(
            catching_rules(conn, pair["a"], pair["b"])
            + catching_rules(conn, pair["b"], pair["a"])
        )
        if rules:
            caught.append((pair["kind"], sorted(rules)))
    assert not caught, f"indistinguishable negative pairs: {caught}"


# ---------------------------------------------------------------------------
# Gate 3: determinism hash over the full pipeline, shuffled insertion order
# ---------------------------------------------------------------------------


def _pipeline_digest(seed: int) -> str:
    patients = list(CORPUS["patients"])
    random.Random(seed).shuffle(patients)
    conn = _indexed_conn(patients)
    match_corpus(conn, f"determinism-{seed}")
    build_membership(conn)

    linkage_json = json.dumps(load_linkage_resources(conn), sort_keys=True)
    membership_rows = sorted(
        conn.execute("SELECT member_patient_id, individual_id FROM patient_membership").fetchall()
    )
    audit_rows = sorted(
        conn.execute(
            "SELECT patient_id, candidate_id, outcome, rule_id, confidence, "
            "CAST(evidence AS VARCHAR) FROM match_audit"
        ).fetchall()
    )

    h = hashlib.sha256()
    h.update(linkage_json.encode("utf-8"))
    h.update(repr(membership_rows).encode("utf-8"))
    h.update(repr(audit_rows).encode("utf-8"))
    return h.hexdigest()


def test_pipeline_determinism_under_shuffled_insertion_order():
    digest_a = _pipeline_digest(seed=1)
    digest_b = _pipeline_digest(seed=2)
    assert digest_a == digest_b, (
        "full pipeline not deterministic under insertion-order shuffle:\n"
        f"{digest_a}\nvs\n{digest_b}"
    )


# ---------------------------------------------------------------------------
# Gate 4: scale smoke (slow-marked, still run)
# ---------------------------------------------------------------------------

FIRSTS = ["Ana", "Luis", "Mara", "Ivan", "Petra", "Kofi", "Mei", "Sven", "Ines", "Tariq"]
LASTS = ["Baker", "Duarte", "Novak", "Osei", "Tanaka", "Weber", "Yilmaz", "Silva", "Rossi", "Khan"]


@pytest.mark.slow
def test_scale_smoke_2000_patients_under_30s():
    import datetime as dt

    conn = duckdb.connect()
    create_matching_tables(conn)
    rng = random.Random(2000)
    base = dt.date(1940, 1, 1)
    for i in range(2000):
        resource = {
            "resourceType": "Patient",
            "id": f"scale-{i:05d}",
            "name": [
                {
                    "use": "official",
                    "family": LASTS[i % len(LASTS)],
                    "given": [FIRSTS[(i // 7) % len(FIRSTS)]],
                }
            ],
            "birthDate": (base + dt.timedelta(days=rng.randrange(20000))).isoformat(),
            "telecom": [{"system": "phone", "value": f"{200 + i % 700}{i % 900:03d}{i % 9999:04d}"}],
            "address": [{"line": [f"{i} Main Street"]}],
            "identifier": [
                {"system": "http://hl7.org/fhir/sid/us-ssn", "value": f"123-45-{i % 10000:04d}"}
            ],
        }
        index_patient(conn, resource)

    probe = {
        "resourceType": "Patient",
        "id": "scale-probe",
        "name": [{"use": "official", "family": LASTS[0], "given": [FIRSTS[0]]}],
        "birthDate": (base + dt.timedelta(days=rng.randrange(20000))).isoformat(),
        "telecom": [{"system": "phone", "value": "9990001111"}],
        "address": [{"line": ["1 Main Street"]}],
        "identifier": [
            {"system": "http://hl7.org/fhir/sid/us-ssn", "value": "123-45-6789"}
        ],
    }
    start = time.monotonic()
    result = match_patient(conn, probe, exclude=frozenset({"scale-probe"}))
    elapsed = time.monotonic() - start
    assert result.outcome in ("match", "no_match", "ambiguous")
    assert elapsed < 30.0, f"scale smoke tripped: match_patient took {elapsed:.1f}s"
