#!/usr/bin/env python3
"""Combine rung results into benchmarks/scaling/SCALING.md.

Headline metric is EXECUTION TIME ONLY. Compile phases (CQL parse, library
translation, population-SQL generation, result conversion) are reported as
diagnostics and are never folded into speedup or ms/patient figures.

fhir4ds rows are MEASURED (median of repeats). clinical-reasoning rows are
EXTRAPOLATED linearly from benchmarks/output/cr_runs.json per-patient means
(5 runs x 2025 QI-Core fixtures, 10-159 patients per measure) — labeled.
"""
from __future__ import annotations

import json
import statistics
import sys
from pathlib import Path

BENCH = Path(__file__).resolve().parent.parent
SCALING = BENCH / "scaling"
RESULTS = SCALING / "results"
CR_RUNS = BENCH / "output" / "cr_runs.json"

sys.path.insert(0, str(SCALING))
from analyze_profiles import operator_attribution, structural_score  # noqa: E402

MEASURE_TITLES = {
    "CMS68": "Documentation of Current Medications (low complexity)",
    "CMS130": "Colorectal Cancer Screening (medium complexity)",
    "CMS2": "Depression Screening and Follow-Up (high complexity)",
}
# Rungs measured at the standard 32GB limit; the 48GB rerun is a sibling entry.
RUNGS = [100, 1000, 5000]
MEMORY_RUNS = [("rung5000", "32GB"), ("rung5000_48g", "48GB")]


def cr_ms_per_patient() -> dict[str, float]:
    data = json.loads(CR_RUNS.read_text())
    by: dict[str, list[float]] = {}
    for r in data:
        if r.get("status") == "success" and r.get("patient_count"):
            by.setdefault(r["measure_id"], []).append(r["execution_ms"] / r["patient_count"])
    return {m: statistics.mean(v) for m, v in by.items()}


# Headline numbers per rung. Rung 5,000 uses the 48GB run because the 32GB
# limit forced spills (see memory-comparison section); rungs 100/1,000 never
# approached 32GB so their 32GB numbers are config-equivalent.
PREFERRED_TAG = {100: "rung100", 1000: "rung1000", 5000: "rung5000_48g"}


def load(tag: str) -> dict | None:
    p = RESULTS / f"{tag}.json"
    return json.loads(p.read_text()) if p.exists() else None


def structural() -> dict[str, dict]:
    out = {}
    for mid in MEASURE_TITLES:
        p = RESULTS / "sql" / f"{mid}.sql"
        if p.exists():
            out[mid] = structural_score(p.read_text())
    return out


def profile_attribution(tag: str, mid: str) -> dict | None:
    p = RESULTS / "profiles" / f"{tag}_{mid}_profile.json"
    return operator_attribution(json.loads(p.read_text())) if p.exists() else None


def us_per_resource(exec_ms: float, resources: int | None) -> float | None:
    return (exec_ms * 1000.0 / resources) if resources else None


def estimated_rows_evaluated(scan_by_type: dict[str, int], type_counts: dict[str, int]) -> int:
    """Sum over scan sites of the rows in that resourceType: the number of
    per-row predicate evaluations the query performs on retrieved rows."""
    return sum(n * type_counts.get(t, 0) for t, n in scan_by_type.items())


def main() -> None:
    cr = cr_ms_per_patient()
    data = {r: load(PREFERRED_TAG.get(r, f"rung{r}")) for r in RUNGS}
    struct = structural()

    L: list[str] = []
    L.append("# Quality-Measure Scaling Benchmark")
    L.append("")
    L.append("*Generated by `benchmarks/scaling/run_measures.py`, "
             "`analyze_profiles.py` and `make_report.py`*")
    L.append("")

    # ---------------- Method ----------------
    L.append("## Method")
    L.append("")
    L.append("**Headline metric is execution time only.** CQL parse, library translation,")
    L.append("population-SQL generation and result conversion are reported separately as")
    L.append("compile diagnostics and are **never** included in speedup or ms/patient figures.")
    L.append("")
    L.append("- **Engine (measured):** fhir4ds compiles each eCQM's CQL to one population SQL")
    L.append("  query (`translate_library_to_population_sql`) over an in-memory DuckDB table of")
    L.append("  FHIR resources. Execution time = median of 3 runs of the same pre-compiled SQL;")
    L.append("  the query is planned/optimised by DuckDB on every execution, so planning is")
    L.append("  included in execution time, compilation is not.")
    L.append("- **Cohorts:** nested deterministic prefixes (sorted bundle order) of one Synthea")
    L.append("  s3 generation: 100 / 1,000 / 5,000 patients; measurement period 2026-01-01..2026-12-31.")
    L.append("  One fresh process per rung; cohort data loaded once per rung from the durable")
    L.append("  `/mnt/d/scaling-data` corpus (never regenerated).")
    L.append("- **Baseline (extrapolated):** clinical-reasoning (Java, HAPI-based) per-patient")
    L.append("  ELM evaluation, linearly extrapolated by patient count from")
    L.append("  `benchmarks/output/cr_runs.json`. CR was not run at these sizes.")
    L.append("- **Memory:** peak process RSS (`ru_maxrss`); a watchdog aborts past 50 GB.")
    L.append("- **Population columns are RAW per-definition truth values** (no CQM attribution")
    L.append("  masking), so Numerator may exceed Denominator on synthetic data; counts are")
    L.append("  sanity signals, not reported measure rates.")
    L.append("")

    # ---------------- Cohorts ----------------
    L.append("## Cohorts")
    L.append("")
    L.append("| Rung | Patients | Resources | Load (s) | Peak RSS (MB) | DuckDB memory_limit |")
    L.append("|------|----------|-----------|----------|---------------|---------------------|")
    for r in RUNGS:
        d = data[r]
        if not d:
            continue
        L.append(f"| {r} | {d['actual_patients']:,} | {d['resources_loaded']:,} "
                 f"| {d['data_load_s']:.0f} | {d['peak_rss_mb']:,.0f} "
                 f"| {d.get('duckdb_memory_limit', '32GB')} |")
    L.append("")
    L.append("The rung-5,000 row is the 48 GB run (no spill). The 32 GB run is preserved")
    L.append("in the memory-comparison section; rungs 100/1,000 never approached the 32 GB")
    L.append("limit, so their numbers are config-equivalent across the two settings.")
    L.append("")

    # ---------------- Memory comparison ----------------
    L.append("## Memory-limit comparison (rung 5000): 32 GB vs 48 GB")
    L.append("")
    L.append("| Limit | CMS68 exec (ms) | CMS130 exec (ms) | CMS2 exec (ms) | Peak RSS (MB) |")
    L.append("|-------|-----------------|------------------|----------------|---------------|")
    base = {}
    for tag, limit in MEMORY_RUNS:
        d = load(tag)
        if not d:
            L.append(f"| {limit} | _not run_ | _not run_ | _not run_ | _not run_ |")
            continue
        vals = []
        for mid in ("CMS68", "CMS130", "CMS2"):
            m = d["measures"].get(mid, {})
            vals.append(f"{m.get('exec_ms_median', 0):,.0f}" if m.get("status") == "success" else "ERROR")
        L.append(f"| {limit} | {vals[0]} | {vals[1]} | {vals[2]} | {d['peak_rss_mb']:,.0f} |")
        base[limit] = d
    if "32GB" in base and "48GB" in base:
        L.append("")
        L.append("Deltas (48 GB vs 32 GB):")
        for mid in ("CMS68", "CMS130", "CMS2"):
            a = base["32GB"]["measures"].get(mid, {})
            b = base["48GB"]["measures"].get(mid, {})
            if a.get("status") == "success" and b.get("status") == "success":
                da = a["exec_ms_median"]
                db = b["exec_ms_median"]
                L.append(f"- **{mid}**: {da:,.0f} ms → {db:,.0f} ms "
                         f"({(db / da - 1) * 100:+.1f}%)")
        L.append(f"- **Peak RSS**: {base['32GB']['peak_rss_mb']:,.0f} MB → "
                 f"{base['48GB']['peak_rss_mb']:,.0f} MB")
    L.append("")

    # ---------------- Exec time table ----------------
    L.append("## Execution time: measured fhir4ds vs extrapolated clinical-reasoning")
    L.append("")
    for mid, title in MEASURE_TITLES.items():
        L.append(f"### {mid} — {title}")
        L.append("")
        L.append("| Patients | fhir4ds exec (ms) | µs/resource | fhir4ds ms/patient "
                 "| CR exec (ms, extrapolated) | CR ms/patient | Speedup (CR / fhir4ds) |")
        L.append("|----------|-------------------|-------------|----------------------|"
                 "----------------------------|---------------|-----------------------|")
        for r in RUNGS:
            d = data[r]
            if not d or mid not in d["measures"]:
                continue
            m = d["measures"][mid]
            if m.get("status") != "success":
                L.append(f"| {r:,} | ERROR | — | — | — | — | — |")
                continue
            ex = m["exec_ms_median"]
            pp = ex / m["patients"]
            upr = us_per_resource(ex, d["resources_loaded"])
            cr_pp = cr.get(mid)
            if cr_pp:
                cr_tot = cr_pp * r
                L.append(f"| {r:,} | {ex:,.0f} | {upr:,.2f} | {pp:.2f} "
                         f"| {cr_tot:,.0f} | {cr_pp:.2f} | {cr_tot / ex:,.0f}x |")
            else:
                L.append(f"| {r:,} | {ex:,.0f} | {upr:,.2f} | {pp:.2f} | — | — | — |")
        L.append("")

    # ---------------- Structural score ----------------
    L.append("## Structural cost score (replaces SQL bytes as the classifier)")
    L.append("")
    L.append("Counted from the generated population SQL. Score weights: scan site 1.0,")
    L.append("SELECT DISTINCT 1.0, json_extract 0.25, date/timestamp CAST 0.5, join 0.5,")
    L.append("derived table 0.5. Valueset/coding-match and interval-call counts are shown")
    L.append("as secondary counters and are **excluded** from the score (see note below).")
    L.append("")
    L.append("| Measure | Scans | Scans by resourceType | SELECT DISTINCT | json_extract "
             "| date casts | joins | derived tables | **Score** | Secondary: valueset/coding | interval |")
    L.append("|---------|-------|----------------------|-----------------|--------------|"
             "------------|-------|----------------|-----------|----------------------------|----------|")
    for mid, s in struct.items():
        by_type = ", ".join(f"{k} {v}" for k, v in s["scan_sites_by_type"].items())
        L.append(f"| {mid} | {s['scan_sites']} | {by_type} | {s['select_distinct']} "
                 f"| {s['json_extract']} | {s['date_casts']} | {s['joins']} "
                 f"| {s['derived_tables']} | **{s['score']:,.0f}** "
                 f"| {s['valueset_or_coding_matches']:,} | {s['interval_predicates']:,} |")
    L.append("")
    # Verification against measured cost at the largest rung
    big = data.get(RUNGS[-1])
    mem_big = load("rung5000_48g") or big
    type_counts = (mem_big or {}).get("type_counts", {})
    if struct:
        L.append("### Does the score predict measured cost?")
        L.append("")
        L.append("`est. rows evaluated` = Σ over scan sites of the row count of that")
        L.append("resourceType in the 5,000-patient cohort — i.e. how many per-row predicate")
        L.append("evaluations the query performs. It is derived from the SQL structure plus")
        L.append("cohort shape, not from timings.")
        L.append("")
        L.append("| Measure | Score | est. rows evaluated | measured exec (ms) | µs/resource "
                 "| µs per evaluated row |")
        L.append("|---------|-------|---------------------|--------------------|-------------|"
                 "---------------------|")
        measured, rows_eval = {}, {}
        for mid in struct:
            m = (mem_big or {}).get("measures", {}).get(mid, {})
            re_ = estimated_rows_evaluated(struct[mid]["scan_sites_by_type"], type_counts)
            rows_eval[mid] = re_
            if m.get("status") == "success":
                upr = us_per_resource(m["exec_ms_median"], (mem_big or {}).get("resources_loaded"))
                per_row = (m["exec_ms_median"] * 1000.0 / re_) if re_ else None
                measured[mid] = upr
                L.append(f"| {mid} | {struct[mid]['score']:,.0f} | {re_:,} "
                         f"| {m['exec_ms_median']:,.0f} | {upr:,.2f} | {per_row:.2f} |")
        L.append("")
        order_score = sorted(struct, key=lambda m: -struct[m]["score"])
        order_rows = sorted(rows_eval, key=lambda m: -rows_eval[m])
        order_measured = sorted(measured, key=lambda m: -measured[m])
        L.append(f"- Score ranking: {' > '.join(order_score)}")
        L.append(f"- Est. rows-evaluated ranking: {' > '.join(order_rows)}")
        L.append(f"- Measured ranking: {' > '.join(order_measured)}")
        ok = order_score == order_measured
        L.append(f"- **Verdict: {'CONFIRMED' if ok else 'REFUTED'}** — the structural score "
                 "reproduces the measured complexity order.")
        if len(order_score) >= 3:
            a, b = order_measured[0], order_measured[1]
            L.append(f"- Magnitude check ({a} vs {b}): score {struct[a]['score'] / struct[b]['score']:.1f}x, "
                     f"rows evaluated {rows_eval[a] / rows_eval[b]:.1f}x, "
                     f"measured cost {measured[a] / measured[b]:.1f}x. Cost decomposes as "
                     f"rows evaluated × per-row predicate cost; the per-row term comes from "
                     "the operator profile (the top scans' pushed-down filters), not from "
                     "static counts.")
        L.append("")
        L.append("Secondary counters do **not** predict cost: CMS2 carries far more")
        L.append("valueset/coding-match and interval calls, yet is much cheaper per resource.")
        L.append("Those calls sit behind selective filters on small row sets; CMS130 spends its")
        L.append("predicate weight on full Observation scans, so the same static call count")
        L.append("costs far more. Row placement (which operator evaluates the expression, over")
        L.append("how many rows) is what the static score cannot see and the profile reveals.")
        L.append("")

    # ---------------- Operator attribution ----------------
    L.append("## Operator-level attribution (EXPLAIN ANALYZE)")
    L.append("")
    L.append("Exclusive time per operator, bucketed; captured once per measure per rung")
    L.append("*after* the timed repetitions (the profiled execution itself is not counted")
    L.append("in the headline numbers).")
    L.append("")
    for tag_label, tag, rung in [("rung 5,000 @48GB", "rung5000_48g", 5000),
                                 ("rung 5,000 @32GB", "rung5000", 5000),
                                 ("rung 1,000", "rung1000", 1000),
                                 ("rung 100", "rung100", 100)]:
        found = False
        rows = []
        d = data.get(rung) if rung in RUNGS else load(tag)
        for mid in MEASURE_TITLES:
            a = profile_attribution(tag, mid)
            if a:
                found = True
                pct = a["buckets_pct"]
                amp = ""
                if d and d.get("resources_loaded") and a.get("rows_scanned"):
                    amp = f"{a['rows_scanned'] / d['resources_loaded']:.1f}x"
                rows.append(
                    f"| {mid} | {a.get('resource_scan_sites_executed', '—')} "
                    f"| {a.get('rows_scanned') or 0:,} | {amp} | "
                    + " | ".join(
                        f"{pct.get(b, 0):.1f}%"
                        for b in ("resource_scans", "other_scans", "joins",
                                  "distinct_aggregate", "expression_eval",
                                  "expression_other", "window", "cte_scan", "order")
                    )
                    + f" | {a.get('peak_temp_dir_mb', 0):,.0f} |"
                )
        if not found:
            continue
        L.append(f"### {tag_label}")
        L.append("")
        L.append("| Measure | scans executed | rows scanned | amplification "
                 "| resource_scans | other_scans | joins | distinct/agg | expr eval "
                 "| expr other | window | CTE | order | peak temp (MB) |")
        L.append("|---------|----------------|--------------|---------------|"
                 "----------------|-------------|-------|--------------|-----------|"
                 "------------|--------|-----|-------|----------------|")
        L.extend(rows)
        L.append("")
    L.append("Caveats: with parallel execution, per-operator timings are summed across")
    L.append("worker threads, so the shares above are relative cost distribution, not")
    L.append("wall-clock seconds (wall time is the measured exec time). Predicate")
    L.append("expressions (fhirpath_text / in_valueset / interval UDFs) are pushed INTO")
    L.append("the scans as filters, so their evaluation cost is attributed to")
    L.append("`resource_scans`, which is why `expr eval` is near zero. `rows scanned` is a")
    L.append("true per-query total: rows read from the `resources` table across ALL retrieve")
    L.append("scans. `amplification` = rows scanned / table rows, i.e. how many times the")
    L.append("corpus is re-read per query.")
    L.append("")
    L.append("**Rung invariance:** amplification is essentially constant across the ladder")
    L.append("(CMS130 41.5x at 100 patients vs 42.0x at 5,000; CMS2 17.8x vs 18.0x; CMS68 6.9x")
    L.append("vs 7.0x), and `scans executed` is identical at every rung. Cost is therefore")
    L.append("O(scan_sites x corpus) with a fixed multiplier — the engine re-reads the whole")
    L.append("corpus once per retrieve CTE, at every scale.")
    L.append("")

    # ---------------- Optimization candidates ----------------
    L.append("## Optimization candidates (evidence-backed, NOT implemented)")
    L.append("")
    L.append("Ranked by expected payoff. Joel ruled these are follow-ups; nothing below is")
    L.append("implemented in this branch.")
    L.append("")
    dev = []
    cms130 = struct.get("CMS130", {})
    a130 = profile_attribution("rung5000_48g", "CMS130") or {}
    a2 = profile_attribution("rung5000_48g", "CMS2") or {}
    a68 = profile_attribution("rung5000_48g", "CMS68") or {}

    def amp(a, d):
        if not a or not d or not d.get("resources_loaded"):
            return "n/a"
        return f"{a['rows_scanned'] / d['resources_loaded']:.1f}x"

    big48 = load("rung5000_48g") or {}
    dev.append(
        f"1. **Per-retrieve shared CTE cache (duplicate retrieve scans).** "
        f"CMS130 executes {a130.get('resource_scan_sites_executed', 0)} resource-table scans "
        f"reading {a130.get('rows_scanned', 0):,} rows from a "
        f"{(big48.get('resources_loaded') or 0):,}-row table "
        f"({amp(a130, big48)} amplification); CMS2 {a2.get('resource_scan_sites_executed', 0)} "
        f"scans / {amp(a2, big48)}; CMS68 {a68.get('resource_scan_sites_executed', 0)} scans / "
        f"{amp(a68, big48)}. Resource scans take "
        f"{a130.get('buckets_pct', {}).get('resource_scans', 0):.1f}% (CMS130), "
        f"{a2.get('buckets_pct', {}).get('resource_scans', 0):.1f}% (CMS2) and "
        f"{a68.get('buckets_pct', {}).get('resource_scans', 0):.1f}% (CMS68) of exclusive "
        f"operator time. Several CQL defines retrieve the same resourceType+filter "
        f"(CMS130: {cms130.get('scan_sites_by_type', {}).get('Encounter', 0)} Encounter, "
        f"{cms130.get('scan_sites_by_type', {}).get('Condition', 0)} Condition, "
        f"{cms130.get('scan_sites_by_type', {}).get('Observation', 0)} Observation, "
        f"{cms130.get('scan_sites_by_type', {}).get('Procedure', 0)} Procedure) and are "
        f"re-emitted as separate full-table scans. A per-(resourceType, filter) retrieve "
        f"cache collapses them."
    )
    dev.append(
        "2. **Move heavy predicate work out of full-type scan filters (row placement).** "
        "CMS130's two most expensive operators are Observation scans whose pushed-down "
        "filter evaluates, per row, nested `CASE`/`fhirpath_text(...)`/`__fhir4ds_py_"
        "intervalEnd(...)`/`cqlSameOrBeforeP(...)` expressions 3-5 times, and emits "
        "**0 rows**. Because the predicates are scan filters they run over every "
        "Observation (2.6M rows at this rung) twice. Precomputing the derived temporal "
        "bounds as retrieve columns (the translator already does this for "
        "`period_start`/`period_end`) and filtering on those columns moves the UDF work "
        "after the cheap selectivity check."
    )
    dev.append(
        "3. **`_patients` CTE still costs a full pass plus two lookups per row.** "
        "The optimizer decorrelates the two scalar `SELECT ... WHERE id = _outer.patient_ref` "
        "subqueries and the `EXISTS` probe into joins, but the CTE still reads the whole "
        "`resources` table (6.19M rows here) to produce 5,000 patient ids. In the CMS68 "
        "profile the `_patients` projection over 6,192,864 rows plus its `HASH_GROUP_BY` "
        "account for ~27% of thread-summed exclusive operator time. Rewriting as one join "
        "against the Patient rows (or a materialized patients table) removes the repeated "
        "lookups."
    )
    dev.append(
        f"4. **JSON→VARCHAR re-serialization at every UDF call site.** The plan shows "
        f"`fhirpath_text(CAST(resource AS VARCHAR), ...)` and "
        f"`in_valueset(CAST(resource AS VARCHAR), ...)` in the pushed-down filters: because "
        f"`resources.resource` is typed JSON, each call re-serializes the document to text. "
        f"CMS130's SQL contains {cms130.get('json_extract', 0)} json_extract and (by grep) "
        f"845 fhirpath_text call sites, 200 date-normalization (`left(replace(...))`) sites "
        f"and 207 interval calls; on the ~29.5M evaluated rows these conversions run inside "
        f"the pushed-down scan filters. Keeping a VARCHAR shadow column (or binding the UDFs to JSON) "
        f"removes the cast."
    )
    dev.append(
        f"5. **`SELECT DISTINCT` over the full JSON blob — DEMOTED, not a major win.** "
        f"Every retrieve CTE dedups on `(patient_ref, resource, <columns>)`. The profile "
        f"shows dedup/aggregation at only "
        f"{a130.get('buckets_pct', {}).get('distinct_aggregate', 0):.1f}% (CMS130), "
        f"{a2.get('buckets_pct', {}).get('distinct_aggregate', 0):.1f}% (CMS2) and "
        f"{a68.get('buckets_pct', {}).get('distinct_aggregate', 0):.1f}% (CMS68) of exclusive "
        f"operator time: after pushed-down filters the surviving row sets are small. Still "
        f"worth deduping on identity rather than payload when candidate 1 lands (it shrinks "
        f"the per-CTE payload), but it should not be prioritized over scans."
    )
    L.extend(dev)
    L.append("")
    L.append("Refuted/withdrawn: counting valueset/coding-match or interval call sites as")
    L.append("complexity drivers (CMS2 has thousands yet is the cheaper measure per resource)")
    L.append("and treating DISTINCT-over-JSON as the primary cost (0.2-4.1% of operator time).")
    L.append("")

    # ---------------- Compile diagnostics ----------------
    L.append("## Compile diagnostics (excluded from headline numbers)")
    L.append("")
    L.append("| Measure | SQL size | Parse (ms) | Library translation (ms) | Population SQL gen (ms) |")
    L.append("|---------|----------|------------|--------------------------|--------------------------|")
    seen = set()
    ref = data.get(RUNGS[0])
    if ref:
        for mid, m in ref["measures"].items():
            if m.get("status") != "success" or mid in seen:
                continue
            seen.add(mid)
            L.append(f"| {mid} | {m['sql_chars'] / 1000:,.0f} KB | {m['parse_ms']:.0f} "
                     f"| {m['library_translation_ms']:,.0f} | {m['sql_generation_ms']:,.0f} |")
    L.append("")
    L.append("Compilation is cohort-independent (one-time per library); execution SQL is reused.")
    L.append("")

    # ---------------- Population sanity ----------------
    L.append("## Population results (sanity only)")
    L.append("")
    L.append("| Measure (rung) | Patients | Populations |")
    L.append("|----------------|----------|-------------|")
    for r in RUNGS:
        d = data[r]
        if not d:
            continue
        for mid, m in d["measures"].items():
            if m.get("status") != "success":
                continue
            pops = ", ".join(f"{k}={v}" for k, v in m["populations"].items())
            L.append(f"| {mid} ({r:,}) | {m['patients']:,} | {pops} |")
    L.append("")

    out = SCALING / "SCALING.md"
    out.write_text("\n".join(L) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
