#!/usr/bin/env python3
"""Combine rung results into benchmarks/scaling/SCALING.md.

Headline metric is EXECUTION TIME ONLY. Compile phases (CQL parse, library
translation, population-SQL generation, result conversion) are reported as
diagnostics and are never folded into speedup or ms/patient figures.

fhir4ds rows are MEASURED (median of repeats) on BOTH DuckDB engine lines
(1.5.6 and 2.0.0). clinical-reasoning rows are EXTRAPOLATED linearly from
benchmarks/output/cr_runs.json per-patient means — labeled as such.
"""
from __future__ import annotations

import json
import statistics
import sys
from pathlib import Path

BENCH = Path(__file__).resolve().parent.parent
SCALING = BENCH / "scaling"
RESULTS = SCALING / "results"
CR_RUNS = BENCH / "output" / "cr_runs.json"

sys.path.insert(0, str(SCALING))
from analyze_profiles import operator_attribution, structural_score  # noqa: E402

MEASURE_TITLES = {
    "CMS68": "Documentation of Current Medications",
    "CMS22": "PCP BP Screening & Follow-Up (medium complexity)",
    "CMS2": "Depression Screening and Follow-Up (high SQL complexity)",
    "CMS130": "Colorectal Cancer Screening (high scan-amplification)",
    "CMS133": "Cataracts BCVA (very high scan-site count)",
}
RUNGS = [100, 1000, 5000]
ENGINES = [("d156", "DuckDB 1.5.6"), ("d20", "DuckDB 2.0.0")]
# 2026-10-29 committed baseline (pre materialization/patients-rewrite) for the
# progress comparison. Artifacts preserved under results/.
BASELINE_TAG = {100: "rung100", 1000: "rung1000", 5000: "rung5000_48g"}


def cr_ms_per_patient() -> dict[str, float]:
    data = json.loads(CR_RUNS.read_text())
    by: dict[str, list[float]] = {}
    for r in data:
        if r.get("status") == "success" and r.get("patient_count"):
            by.setdefault(r["measure_id"], []).append(r["execution_ms"] / r["patient_count"])
    return {m: statistics.mean(v) for m, v in by.items()}


def load(tag: str) -> dict | None:
    p = RESULTS / f"{tag}.json"
    return json.loads(p.read_text()) if p.exists() else None


def structural() -> dict[str, dict]:
    out = {}
    for mid in MEASURE_TITLES:
        p = RESULTS / "sql" / f"{mid}.sql"
        if p.exists():
            out[mid] = structural_score(p.read_text())
    return out


def med(d: dict, mid: str) -> float | None:
    m = d["measures"].get(mid)
    if m and m.get("status") == "success":
        return m["exec_ms_median"]
    return None


def main() -> None:
    cr = cr_ms_per_patient()
    data = {(e, r): load(f"{e}_rung{r}") for e, _ in ENGINES for r in RUNGS}
    base = {r: load(BASELINE_TAG[r]) for r in RUNGS}
    struct = structural()

    L: list[str] = []
    A = L.append
    A("# Quality-Measure Scaling Benchmark")
    A("")
    A("*Generated by `benchmarks/scaling/run_measures.py`, `analyze_profiles.py` and `make_report.py`*")
    A("")
    A("## Method")
    A("")
    A("**Headline metric is execution time only.** CQL parse, library translation,")
    A("population-SQL generation and result conversion are reported separately as")
    A("compile diagnostics and are **never** included in speedup or ms/patient figures.")
    A("")
    A("- **Engine (measured):** fhir4ds compiles each eCQM's CQL to one population SQL")
    A("  query (`translate_library_to_population_sql`) over an in-memory DuckDB table of")
    A("  FHIR resources, run identically on **both DuckDB 1.5.6 and 2.0.0**. Execution")
    A("  time = median of 3 runs of the same pre-compiled SQL; the query is planned/")
    A("  optimised by DuckDB on every execution, so planning is included in execution")
    A("  time, compilation is not.")
    A("- **Measures:** CMS68 (low), CMS22 (medium), CMS2 (high SQL complexity), CMS130")
    A("  (high scan amplification), CMS133 (very high scan-site count: ~110 distinct")
    A("  Condition valueset retrieves). The first three match the 2026-10-29 baseline;")
    A("  CMS22/CMS133 were added 2026-11-13.")
    A("- **Cohorts:** nested deterministic prefixes (sorted bundle order) of one Synthea")
    A("  s3 generation: 100 / 1,000 / 5,000 patients; measurement period 2026-01-01..2026-12-31.")
    A("  One fresh process per rung per engine; cohort data loaded once per rung from the")
    A("  durable `/mnt/d/scaling-data` corpus (never regenerated).")
    A("- **Baseline (extrapolated):** clinical-reasoning (Java, HAPI-based) per-patient")
    A("  ELM evaluation, linearly extrapolated by patient count from")
    A("  `benchmarks/output/cr_runs.json`. CR was not run at these sizes.")
    A("- **Memory:** peak process RSS (`ru_maxrss`); a watchdog aborts past 50 GB.")
    A("  Rungs 100/1,000 ran at `memory_limit=32GB`, rung 5,000 at 48 GB (no spill).")
    A("- **Population columns are RAW per-definition truth values** (no CQM attribution")
    A("  masking), so Numerator may exceed Denominator on synthetic data; counts are")
    A("  sanity signals, not reported measure rates. CMS133 evaluates to empty")
    A("  populations on this cohort (no cataracts surgery patients in Synthea s3) but")
    A("  still executes the full query — valid for execution-cost measurement.")
    A("")

    # Cohorts
    A("## Cohorts")
    A("")
    A("| Engine | Rung | Patients | Resources | Load (s) | Peak RSS (MB) | memory_limit |")
    A("|--------|------|----------|-----------|----------|---------------|--------------|")
    for e, elabel in ENGINES:
        for r in RUNGS:
            d = data[(e, r)]
            if d:
                A(f"| {elabel} | {r} | {d['actual_patients']:,} | {d['resources_loaded']:,} "
                  f"| {d['data_load_s']:.0f} | {d['peak_rss_mb']:,.0f} "
                  f"| {d.get('duckdb_memory_limit', '')} |")
    A("")

    # Progress vs baseline (trio only — the baseline shipped 3 measures)
    A("## Progress vs the 2026-10-29 baseline (DuckDB 1.5.6 line)")
    A("")
    A("The committed baseline predates the `_rt_<Type>` shared-type materialization,")
    A("the `_patients` CTE rewrite, and the disambiguation-macro work. Same corpus,")
    A("same cohorts, same 3 measures:")
    A("")
    A("| Measure | Rung | 2026-10-29 (ms) | current (ms) | speedup |")
    A("|---------|------|------------------|--------------|---------|")
    for mid in ("CMS68", "CMS130", "CMS2"):
        for r in RUNGS:
            old = med(base[r], mid) if base[r] else None
            new = med(data[("d156", r)], mid)
            if old and new:
                A(f"| {mid} | {r:,} | {old:,.0f} | {new:,.0f} | {old / new:.1f}x |")
    A("")
    rss_old = base[5000]["peak_rss_mb"] if base[5000] else None
    rss_new = data[("d156", 5000)]["peak_rss_mb"] if data[("d156", 5000)] else None
    if rss_old and rss_new:
        A(f"Peak RSS at rung 5,000: {rss_old:,.0f} MB → {rss_new:,.0f} MB.")
    A("")

    # Execution tables
    A("## Execution time: measured fhir4ds vs extrapolated clinical-reasoning")
    A("")
    for mid in MEASURE_TITLES:
        crpp = cr.get(mid)
        A(f"### {mid} — {MEASURE_TITLES[mid]}")
        A("")
        A("| Patients | 1.5.6 exec (ms) | 2.0.0 exec (ms) | fhir4ds ms/patient (best) | CR ms/patient | Speedup (CR / best) |")
        A("|----------|-----------------|-----------------|----------------------------|---------------|--------------------|")
        for r in RUNGS:
            m156 = med(data[("d156", r)], mid)
            m20 = med(data[("d20", r)], mid)
            best = min(x for x in (m156, m20) if x is not None) if (m156 or m20) else None
            if best is None:
                continue
            A(f"| {r:,} | {m156:,.0f} | {m20:,.0f} | {best / r:.2f} "
              f"| {crpp and f'{crpp:.2f}'} | {crpp and f'{crpp * r / best:,.0f}x'} |")
        A("")

    # Engine comparison
    A("## Engine comparison: DuckDB 1.5.6 vs 2.0.0 (median exec ms)")
    A("")
    A("| Measure | 100: 1.5.6 / 2.0 | 1,000: 1.5.6 / 2.0 | 5,000: 1.5.6 / 2.0 | 5k delta |")
    A("|---------|-------------------|----------------------|----------------------|-----------|")
    for mid in MEASURE_TITLES:
        cells = []
        d5 = None
        for r in RUNGS:
            m156 = med(data[("d156", r)], mid)
            m20 = med(data[("d20", r)], mid)
            cells.append(f"{m156:,.0f} / {m20:,.0f}")
            if r == 5000 and m156 and m20:
                d5 = (m20 / m156 - 1) * 100
        A(f"| {mid} | " + " | ".join(cells) + f" | {d5 and f'{d5:+.1f}%'} |")
    A("")
    A("The engines split by workload shape: DuckDB 2.0.0 is dramatically faster")
    A("on the scan-heavy measures (CMS130 −90.6%, CMS133 −88.7%, CMS68 −52.5%) but")
    A("regresses CMS2 (~10x) and CMS22 (+24%) — the 1.5 MB single-query SQL shape")
    A("with thousands of pushed-down predicates. Both engine lines ship the same")
    A("generated SQL; per-measure engine choice is a deployment decision until the")
    A("2.0 planner regression on very large SQL is understood.")
    A("")

    # Structural score
    A("## Structural cost score")
    A("")
    A("Counted from the generated population SQL. Score weights: scan site 1.0,")
    A("SELECT DISTINCT 1.0, json_extract 0.25, date/timestamp CAST 0.5, join 0.5,")
    A("derived table 0.5.")
    A("")
    A("| Measure | Scans | SELECT DISTINCT | json_extract | date casts | joins | derived | **Score** |")
    A("|---------|-------|-----------------|--------------|------------|-------|---------|-----------|")
    ranked = sorted(struct.items(), key=lambda kv: kv[1].get("score", 0))
    for mid, s in ranked:
        A(f"| {mid} | {s.get('scan_sites')} | {s.get('select_distinct')} | {s.get('json_extract')} "
          f"| {s.get('date_casts')} | {s.get('joins')} | {s.get('derived_tables')} | **{s.get('score')}** |")
    A("")
    # prediction check vs measured 5k d156
    A("Score vs measured cost @5k (1.5.6): the score ranks CMS68/CMS22/CMS133/")
    A("CMS130 consistently, but CMS2 is the standing outlier — thousands of")
    A("`json_extract` sites that sit behind selective filters on small row sets")
    A("(the same refutation the 2026-10-29 report recorded; row placement is what")
    A("the static score cannot see).")
    A("")
    A("| Measure | Score | measured 1.5.6 @5k (ms) | ms/resource |")
    A("|---------|-------|--------------------------|-------------|")
    d5 = data[("d156", 5000)]
    nres = d5["resources_loaded"] if d5 else 0
    for mid, s in ranked:
        m = med(d5, mid)
        if m:
            A(f"| {mid} | {s.get('score')} | {m:,.0f} | {m * 1000 / nres:.2f} |")
    A("")

    # Operator attribution (5k, both engines)
    A("## Operator-level attribution (EXPLAIN ANALYZE, rung 5,000)")
    A("")
    for e, elabel in ENGINES:
        A(f"### {elabel}")
        A("")
        A("| Measure | scan sites | rows scanned | expr eval | resource scans | distinct/agg |")
        A("|---------|------------|--------------|-----------|----------------|--------------|")
        d5e = data[(e, 5000)]
        for mid in MEASURE_TITLES:
            p = RESULTS / "profiles" / f"{e}_rung5000_{mid}_profile.json"
            m = d5e["measures"].get(mid) if d5e else None
            if not p.exists() or not m or m.get("status") != "success":
                continue
            att = operator_attribution(json.loads(p.read_text()))
            bp = att.get("buckets_pct", {})
            rows = m["profile"].get("rows_scanned") or 0
            A(f"| {mid} | {att.get('resource_scan_sites_executed') or '?'} | {rows:,} "
              f"| {bp.get('expression_eval', 0):.1f}% | {bp.get('resource_scans', 0):.1f}% "
              f"| {bp.get('distinct_aggregate', 0):.1f}% |")
        A("")
    A("With parallel execution, per-operator timings are summed across worker")
    A("threads — the shares above are relative cost distribution, not wall-clock.")
    A("`rows scanned` comes from the DuckDB 1.5 profile export; the 2.0 profile")
    A("JSON does not expose a per-query cumulative total (0 = not available).")
    A("")
    A("**Attribution shift vs the 2026-10-29 report:** resource scans were 64–99.5%")
    A("of exclusive operator time then; now the dominant bucket on BOTH engines is")
    A("**expression evaluation** — the `fhirpath_text`/`in_valueset`/interval")
    A("predicates pushed into scan filters, evaluated over full type partitions")
    A("before selectivity. The scan-count amplification itself was fixed")
    A("(`_rt_<Type>` + identity-deduped retrieve CTEs); what remains is WHERE the")
    A("predicates run, not how many scans exist. That is optimization candidate 1")
    A("below and the next engineering target.")
    A("")

    # Compile diagnostics
    A("## Compile diagnostics (excluded from headline numbers)")
    A("")
    A("| Measure | SQL size | Parse (ms) | Library translation (ms) | Population SQL gen (ms) |")
    A("|---------|----------|------------|--------------------------|--------------------------|")
    d1k = data[("d156", 1000)]
    for mid in MEASURE_TITLES:
        m = d1k["measures"].get(mid)
        if m and m.get("status") == "success":
            A(f"| {mid} | {m['sql_chars'] // 1024} KB | {m['parse_ms']:.0f} "
              f"| {m['library_translation_ms']:,.0f} | {m['sql_generation_ms']:,.0f} |")
    A("")
    A("Compilation is cohort-independent (one-time per library); execution SQL is reused.")
    A("")

    # Candidates
    A("## Optimization candidates (updated 2026-11-13)")
    A("")
    A("**Shipped since the 2026-10-29 report** (evidence: the progress table above):")
    A("")
    A("1. `_patients` CTE rewrite (old candidate 3) — single Patient-row scan, no")
    A("   per-row correlated lookups. The old HASH_JOIN/DELIM_JOIN cost families are")
    A("   gone from the profiles.")
    A("2. `_rt_<Type>` shared base CTEs — one table scan per resource type per query")
    A("   instead of one per retrieve CTE.")
    A("3. Retrieve CTEs deduplicated by identity key (type+valueset+profile).")
    A("")
    A("**Remaining, evidence-backed, NOT implemented:**")
    A("")
    A("1. **Predicate row placement (old candidate 2).** Expensive `fhirpath`/")
    A("   `in_valueset` predicates are pushed into scan filters and evaluated over")
    A("   full type partitions before selectivity; fresh rung-1,000 CMS68 profile")
    A("   shows a 240 ms filter emitting 0 rows (3x its scan) and a 650 ms scan.")
    A("   Precomputing derived temporal bounds as retrieve columns (as the translator")
    A("   already does for `period_start`/`period_end`) moves UDF work behind the")
    A("   cheap selectivity check. This is the next optimization target.")
    A("2. **JSON→VARCHAR re-serialization at UDF call sites (old candidate 4).**")
    A("   `fhirpath_text(CAST(resource AS VARCHAR), ...)` re-serializes the document")
    A("   per call; a VARCHAR shadow column (or JSON-bound UDFs) removes the cast.")
    A("3. **`SELECT DISTINCT` over identity (old candidate 5, demoted).** Dedup on")
    A("   `(patient_ref, id)` instead of the full payload — worthwhile only alongside")
    A("   candidate 1; still 0.2–13% of operator time.")
    A("")
    A("Refuted/withdrawn: counting valueset/coding-match or interval call sites as")
    A("complexity drivers; treating DISTINCT-over-JSON as the primary cost.")
    A("")

    # Population sanity
    A("## Population results (sanity only)")
    A("")
    d5 = data[("d156", 5000)]
    for mid in MEASURE_TITLES:
        m = d5["measures"].get(mid)
        if m and m.get("status") == "success":
            pops = ", ".join(f"{k}={v}" for k, v in m["populations"].items())
            A(f"- {mid} (5,000): {pops}")
    A("")

    out = SCALING / "SCALING.md"
    out.write_text("\n".join(L) + "\n")
    print(f"wrote {out} ({len(L)} lines)")


if __name__ == "__main__":
    main()
